"""Generate the engine-embedded interface module crates/orna-hir/interface/sys.orna.

The source of truth for the `sys` surface is the sys catalogue
(crates/orna-sys-id/catalogue/sys-1.1.0.json). This script derives the body-less
`native fn` declarations and the nominal types they reference, so that typing a
`sys` call needs no second type language (docs/design/hir.md, section H2).

Usage:
    scripts/gen_interface.py          write crates/orna-hir/interface/sys.orna
    scripts/gen_interface.py --check  exit 1 when the checked-in file is stale
"""

import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
CATALOGUE = ROOT / "crates/orna-sys-id/catalogue/sys-1.1.0.json"
OUTPUT = ROOT / "crates/orna-hir/interface/sys.orna"

# Built-in type names the checker already resolves (system_api.rs built-in list).
BUILTINS = {
    "Blob", "Bool", "Decimal", "Digest", "Duration", "Instant", "Int", "Locale", "Path",
    "PresentContext", "PresentTree", "Query", "Relation", "Str", "TimeZone", "Unit", "Null",
    "Float", "Date",
}

# Catalogue effect -> Orna effect class (Main decision, csenl.17 review).
EFFECT_CLASS = {"read": "table_read", "admin": "storage_admin", "invoke": "runtime_admin"}

HEADER = """\
// Generated by scripts/gen_interface.py from crates/orna-sys-id/catalogue/sys-1.1.0.json.
// Do not edit by hand. Regenerate with `python3 scripts/gen_interface.py`.
//
// Engine-embedded `sys` interface (D12): body-less `native fn` declarations
// are admitted only in this module. Opaque identifiers are empty nominal
// bodies because the spec has no body-less opaque declaration (ORNA-NOMINAL-004).
"""


def fail(message):
    sys.exit(f"gen_interface: {message}")


def strip_sys(text):
    """Rewrite catalogue qualified names into module-local names."""
    return re.sub(r"\bsys\.", "", text)


def pascal(text):
    return "".join(part[:1].upper() + part[1:] for part in re.split(r"[_.]", text) if part)


def snake(text):
    return re.sub(r"(?<!^)(?=[A-Z])", "_", text).lower()


def variant_name(label):
    """Derive the binding variant (and so the Orna name) from a catalogue label.

    `sys.admin.checkout(SnapshotRef)` -> `AdminCheckoutSnapshotRef`; `sys.invoke<T>` -> `InvokeT`.
    Matches the names in crates/orna-evaluator/src/sys_bindings.rs.
    """
    match = re.fullmatch(r"sys((?:\.[A-Za-z_]\w*)+)(?:[(<]([^)>]*)[)>])?", label)
    if not match:
        fail(f"unrecognised sys label `{label}`")
    segments = match.group(1)[1:].split(".")
    overload = match.group(2)
    return pascal(".".join(segments)) + (pascal(overload) if overload else "")


def split_top_level(text, separator):
    # Split on `separator` where angle, square and paren depth is zero.
    parts, depth, start, index = [], 0, 0, 0
    while index < len(text):
        char = text[index]
        if char in "<[(":
            depth += 1
        elif char in ">])":
            depth -= 1
        elif depth == 0 and text.startswith(separator, index):
            parts.append(text[start:index])
            index += len(separator)
            start = index
            continue
        index += 1
    parts.append(text[start:])
    return parts


def declared_names(catalogue):
    names = {}
    for identifier in catalogue["opaque_identifiers"]:
        names[strip_sys(identifier)] = "opaque"
    for value in catalogue["value_types"]:
        names[strip_sys(value["name"]).split("<")[0]] = "value"
    for relation in catalogue["relations"]:
        names[strip_sys(relation["name"])] = "relation"
    for alias in catalogue["reference_aliases"]:
        names[strip_sys(alias["name"])] = "alias"
    for enum in catalogue["enums"]:
        names[strip_sys(enum)] = "enum"
    return names


def check_type_tokens(text, known, context):
    for token in re.findall(r"\b[A-Z][A-Za-z0-9_]*\b", text):
        if token not in known and token not in BUILTINS and token not in {"T", "G"}:
            fail(f"{context}: type `{token}` is neither declared nor built in")


def emit_type_declarations(catalogue, known):
    lines = []
    for identifier in catalogue["opaque_identifiers"]:
        lines.append(f"pub type {strip_sys(identifier)} {{}}")
        lines.append("")
    for name, variants in catalogue["enums"].items():
        lines.append(f"pub enum {strip_sys(name)} {{")
        lines.extend(f"    {variant}," for variant in variants)
        lines.append("}")
        lines.append("")
    for value in catalogue["value_types"]:
        name = strip_sys(value["name"]).split("<")[0]
        generics = value.get("type_parameters") or []
        head = name + (f"<{', '.join(generics)}>" if generics else "")
        public = value["kind"] == "record" or value["kind"] == "record-generic"
        fields = value.get("fields") or []
        if not fields:
            lines.append(f"pub type {head} {{}}")
            lines.append("")
            continue
        lines.append(f"pub type {head} {{")
        for field in fields:
            field_type = strip_sys(field["type"])
            check_type_tokens(field_type, known, f"{name}.{field['name']}")
            visibility = "pub " if public else ""
            lines.append(f"    {visibility}{field['name']}: {field_type},")
        lines.append("}")
        lines.append("")
    for relation in catalogue["relations"]:
        name = strip_sys(relation["name"])
        lines.append(f"pub type {name} {{")
        for field in relation["fields"]:
            field_type = strip_sys(field["type"])
            check_type_tokens(field_type, known, f"{name}.{field['name']}")
            lines.append(f"    pub {field['name']}: {field_type},")
        lines.append("}")
        lines.append("")
    for alias in catalogue["reference_aliases"]:
        name = strip_sys(alias["name"])
        definition = strip_sys(alias["definition"])
        check_type_tokens(definition, known, name)
        lines.append(f"pub type {name} = {definition};")
        lines.append("")
    return lines


def emit_native_functions(catalogue, known):
    lines = []
    seen = {}
    for function in catalogue["functions"]:
        label = function["name"]
        variant = variant_name(label)
        orna_name = snake(variant)
        if orna_name in seen:
            fail(f"native name `{orna_name}` from `{label}` collides with `{seen[orna_name]}`")
        seen[orna_name] = label
        signature = function["signature"]
        if not signature.startswith("fn "):
            fail(f"{label}: signature does not start with `fn `")
        body = signature[3:]
        head, _, rest = body.partition("(")
        generics = ""
        generic_match = re.fullmatch(r"sys\.[\w.]+<([^>]*)>", head)
        if generic_match:
            generics = f"<{generic_match.group(1)}>"
        elif not re.fullmatch(r"sys\.[\w.]+", head):
            fail(f"{label}: unrecognised function head `{head}`")
        params_text, _, result_text = rest.rpartition("): ")
        if not result_text:
            fail(f"{label}: missing result type")
        parameters = []
        if params_text:
            for part in split_top_level(params_text, ", "):
                param_match = re.fullmatch(r"(\w+): (.+?)(?: = (.+))?", part)
                if not param_match:
                    fail(f"{label}: unrecognised parameter `{part}`")
                param_name, param_type, default = param_match.groups()
                param_type = strip_sys(param_type)
                check_type_tokens(param_type, known | {g.strip() for g in generics.strip("<>").split(",") if g}, label)
                text = f"{param_name}: {param_type}"
                if default is not None:
                    text += f" = {strip_sys(default)}"
                parameters.append(text)
        result = strip_sys(result_text)
        check_type_tokens(result, known | {g.strip() for g in generics.strip("<>").split(",") if g}, label)
        effect = EFFECT_CLASS.get(function["effect"])
        if effect is None:
            fail(f"{label}: unknown effect `{function['effect']}`")
        lines.append(f"// {label}")
        lines.append(f"pub native fn {orna_name}{generics}({', '.join(parameters)}): {result} effect {effect};")
        lines.append("")
    return lines


def render():
    catalogue = json.loads(CATALOGUE.read_text(encoding="utf-8"))
    known = set(declared_names(catalogue))
    body = emit_type_declarations(catalogue, known) + emit_native_functions(catalogue, known)
    text = HEADER + "\n" + "\n".join(body).rstrip() + "\n"
    if not text.isascii():
        fail("generated interface is not plain ASCII")
    return text


def main(argv):
    text = render()
    if "--check" in argv:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != text:
            print(f"gen_interface: {OUTPUT.relative_to(ROOT)} is stale; run scripts/gen_interface.py", file=sys.stderr)
            return 1
        return 0
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
