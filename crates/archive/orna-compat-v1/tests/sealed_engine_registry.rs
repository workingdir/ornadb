#[test]
fn sealed_function_bytes_and_names_are_pinned() {
    assert_eq!(EngineFunction::ALL.len(), SEALED_FUNCTION_BYTES.len());
    assert_eq!(SYSTEM_FUNCTIONS.len(), SEALED_FUNCTION_BYTES.len());
    for (index, (label, bytes)) in SEALED_FUNCTION_BYTES.iter().enumerate() {
        let generated = EngineFunction::from_label(label).expect("catalogue label resolves");
        assert_eq!(generated, EngineFunction::ALL[index], "{label}");
        assert_eq!(generated.label(), *label, "{label}");
        assert_eq!(generated.function_id(), *bytes, "{label}");
        let definition = SYSTEM_FUNCTIONS[index];
        assert_eq!(definition.id(), FunctionId::from_bytes(*bytes), "{label}");
        assert_eq!(definition.name_parts().join("."), *label, "{label}");
        let name = QualifiedSemanticName::new(definition.name_parts().iter().copied())
            .expect("catalogue name");
        let resolved = system_function_by_name(&name).expect("name resolves");
        assert_eq!(resolved.id(), definition.id(), "{label}");
    }
    for function in EngineFunction::ALL {
        let name = QualifiedSemanticName::new(function.name_parts().iter().copied())
            .expect("catalogue name");
        assert!(
            system_function_by_name(&name).is_some(),
            "{} must resolve by name",
            function.label()
        );
    }
}
